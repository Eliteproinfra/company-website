/**
 * GET /uploads/<folder>/<file> — serves an admin-uploaded image off disk.
 *
 * WHY THIS EXISTS, given the files already sit under `public/uploads`:
 *
 * `next start` resolves the public directory from a snapshot taken when the
 * process boots. A file written after boot — which is every admin upload —
 * is not in that snapshot, so Next's own static handler 404s it until the
 * process restarts. Verified against next@16.4.0: copy a file into
 * public/uploads with the server running and it 404s; restart without
 * rebuilding and the same URL returns 200.
 *
 * nginx hides half of that in production. It serves /uploads/ straight off
 * `shared/uploads` and never consults Node (deploy/nginx-aws.conf), so a plain
 * <img> — the admin's own preview — loads fine. But <Image> on the public
 * pages requests /_next/image, and the optimizer resolves a relative src by
 * replaying it through Next's *internal* handler, which nginx never sees. That
 * hit the boot snapshot, 404'd, and the optimizer turned it into a broken
 * image: the photo saved, the card rendered, only the picture was missing
 * until the next deploy restarted PM2 and the snapshot picked it up.
 *
 * A route handler runs per request and reads the file then, so there is no
 * snapshot to be stale. For files that *were* in the boot snapshot the static
 * handler still answers first and this never runs; it is the fallthrough.
 */
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { UPLOAD_CONTENT_TYPES, uploadsRoot } from "@/lib/uploads";

// Reading the filesystem per request is the entire point — a prerendered or
// cached response would reintroduce the staleness this route exists to fix.
export const dynamic = "force-dynamic";
export const runtime = "nodejs";

/** Shared by every response, hit or miss, so a 404 cannot be sniffed either. */
const SECURITY_HEADERS = {
  // These are user-supplied bytes. Never let a browser re-interpret one as
  // HTML or script — same reasoning as the /uploads/ block in the nginx conf.
  "X-Content-Type-Options": "nosniff",
  "Content-Security-Policy": "default-src 'none'; sandbox",
};

function notFound(): Response {
  return new Response("Not found", {
    status: 404,
    headers: { ...SECURITY_HEADERS, "Content-Type": "text/plain" },
  });
}

export async function GET(
  request: Request,
  context: RouteContext<"/uploads/[...path]">
): Promise<Response> {
  const segments = (await context.params).path;

  // The stored name is generated by the upload route, so a legitimate path is
  // always exactly <folder>/<file> of plain name characters. Anything else —
  // "..", a separator, a leading dot, extra depth — is refused before it can
  // reach path.join rather than normalised into something safe-looking.
  if (segments.length !== 2) return notFound();
  if (!segments.every((segment) => /^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(segment))) {
    return notFound();
  }
  if (segments.some((segment) => segment.includes(".."))) return notFound();

  const extension = path.extname(segments[1]).slice(1).toLowerCase();
  const contentType = UPLOAD_CONTENT_TYPES[extension];
  // Only the image types the upload route can produce are served. If anything
  // else ever lands in this directory it stays unreachable over HTTP.
  if (!contentType) return notFound();

  const filePath = path.join(uploadsRoot(), segments[0], segments[1]);

  let buffer: Buffer;
  try {
    buffer = await readFile(filePath);
  } catch {
    // ENOENT is the ordinary case — a deleted image still referenced by a row.
    // Anything else (EACCES, EISDIR) is equally not a servable image, and the
    // reason must not be echoed back: it would disclose the layout on disk.
    return notFound();
  }

  // Upload names already carry 8 random bytes and are never reused, so the
  // body for a given URL is immutable. An ETag still earns its keep for the
  // image optimizer, which revalidates its own cache entries against it.
  const etag = `"${createHash("sha1").update(buffer).digest("base64")}"`;
  if (request.headers.get("if-none-match") === etag) {
    return new Response(null, { status: 304, headers: { ...SECURITY_HEADERS, ETag: etag } });
  }

  return new Response(new Uint8Array(buffer), {
    headers: {
      ...SECURITY_HEADERS,
      "Content-Type": contentType,
      "Content-Length": String(buffer.byteLength),
      ETag: etag,
      // Matches the nginx /uploads/ block so the two paths to the same bytes
      // do not disagree about how long they may be cached.
      "Cache-Control": "public, max-age=2592000",
    },
  });
}
